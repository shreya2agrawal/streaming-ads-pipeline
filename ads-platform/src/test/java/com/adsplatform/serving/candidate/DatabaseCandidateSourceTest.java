package com.adsplatform.serving.candidate;

import static org.assertj.core.api.Assertions.assertThat;
import static org.mockito.ArgumentMatchers.any;
import static org.mockito.ArgumentMatchers.anyCollection;
import static org.mockito.ArgumentMatchers.eq;
import static org.mockito.Mockito.never;
import static org.mockito.Mockito.verify;
import static org.mockito.Mockito.when;

import java.math.BigDecimal;
import java.time.Instant;
import java.time.LocalDate;
import java.util.List;
import java.util.Optional;
import java.util.Set;

import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.extension.ExtendWith;
import org.mockito.InjectMocks;
import org.mockito.Mock;
import org.mockito.junit.jupiter.MockitoExtension;
import org.springframework.test.util.ReflectionTestUtils;

import com.adsplatform.campaign.Campaign;
import com.adsplatform.campaign.Campaign.CampaignStatus;
import com.adsplatform.creative.Creative;
import com.adsplatform.creative.CreativeRepository;
import com.adsplatform.creative.CreativeSafetyStatus;
import com.adsplatform.creative.CreativeStatus;
import com.adsplatform.creative.CreativeType;
import com.adsplatform.placement.DeviceType;
import com.adsplatform.placement.Placement;
import com.adsplatform.placement.PlacementRepository;
import com.adsplatform.placement.PlacementType;
import com.adsplatform.serving.model.AdRequestContext;
import com.adsplatform.serving.model.CandidateAd;

@ExtendWith(MockitoExtension.class)
class DatabaseCandidateSourceTest {

    @Mock
    private PlacementRepository placementRepository;

    @Mock
    private CreativeRepository creativeRepository;

    @InjectMocks
    private DatabaseCandidateSource candidateSource;

    // 2026-10-15 at noon UTC
    private static final Instant REQUESTED_AT = Instant.parse("2026-10-15T12:00:00Z");

    private static AdRequestContext request() {
        return new AdRequestContext(
                "request-1", 1L, DeviceType.TV, "show-101",
                "viewer-1", Set.of(), 2, REQUESTED_AT);
    }

    private static Placement placement() {
        Placement placement = Placement.create(
                "Pre-roll short", PlacementType.PRE_ROLL, 2, 15,
                Set.of(DeviceType.TV), Set.of(CreativeType.VIDEO));
        placement.activate();
        // The id is generated by the database; set it for the test.
        ReflectionTestUtils.setField(placement, "id", 1L);
        return placement;
    }

    private static Campaign campaign(long id) {
        return Campaign.builder()
                .id(id)
                .name("Campaign " + id)
                .advertiser("Northpeak")
                .agency("Direct")
                .budget(new BigDecimal("1000.00"))
                .flightStart(LocalDate.of(2026, 10, 1))
                .flightEnd(LocalDate.of(2026, 11, 25))
                .status(CampaignStatus.ACTIVE)
                .bidCpc(new BigDecimal("1.50"))
                .build();
    }

    private static Creative video(long id, Campaign campaign, Integer seconds) {
        return Creative.builder()
                .id(id)
                .campaign(campaign)
                .name("Creative " + id)
                .creativeType(CreativeType.VIDEO)
                .mediaUrl("https://cdn.example.com/" + id + ".mp4")
                .destinationUrl("https://advertiser.example.com")
                .contentText("Ad text")
                .durationSeconds(seconds)
                .status(CreativeStatus.ACTIVE)
                .safetyStatus(CreativeSafetyStatus.APPROVED)
                .build();
    }

    private void stubQuery(List<Creative> result) {
        when(creativeRepository.findServableCreatives(
                any(), any(), any(), any(), any(), anyCollection()))
                .thenReturn(result);
    }

    @Test
    void unknownPlacementReturnsNothingWithoutQuerying() {
        when(placementRepository.findById(1L)).thenReturn(Optional.empty());

        assertThat(candidateSource.findCandidates(request())).isEmpty();

        verify(creativeRepository, never()).findServableCreatives(
                any(), any(), any(), any(), any(), anyCollection());
    }

    @Test
    void mapsEachCreativeToACandidate() {
        when(placementRepository.findById(1L)).thenReturn(Optional.of(placement()));
        stubQuery(List.of(video(11L, campaign(1L), 15)));

        List<CandidateAd> candidates = candidateSource.findCandidates(request());

        assertThat(candidates).hasSize(1);
        CandidateAd candidate = candidates.get(0);
        assertThat(candidate.campaign().bidCpc()).isEqualByComparingTo("1.50");
        assertThat(candidate.creative().id()).isEqualTo(11L);
        assertThat(candidate.placement().maxAdDurationSeconds()).isEqualTo(15);
    }

    @Test
    void queriesWithStatusesDateMarginAndPlacementTypes() {
        when(placementRepository.findById(1L)).thenReturn(Optional.of(placement()));
        stubQuery(List.of());

        candidateSource.findCandidates(request());

        verify(creativeRepository).findServableCreatives(
                eq(CampaignStatus.ACTIVE),
                eq(CreativeStatus.ACTIVE),
                eq(CreativeSafetyStatus.APPROVED),
                eq(LocalDate.of(2026, 10, 14)),
                eq(LocalDate.of(2026, 10, 16)),
                eq(Set.of(CreativeType.VIDEO)));
    }

    @Test
    void skipsBadRowAndKeepsTheRest() {
        when(placementRepository.findById(1L)).thenReturn(Optional.of(placement()));
        Campaign campaign = campaign(1L);
        // A video without a duration cannot become a snapshot.
        stubQuery(List.of(video(11L, campaign, null), video(12L, campaign, 15)));

        List<CandidateAd> candidates = candidateSource.findCandidates(request());

        assertThat(candidates).extracting(candidate -> candidate.creative().id())
                .containsExactly(12L);
    }

    @Test
    void creativesOfOneCampaignShareOneSnapshot() {
        when(placementRepository.findById(1L)).thenReturn(Optional.of(placement()));
        Campaign campaign = campaign(1L);
        stubQuery(List.of(video(11L, campaign, 15), video(12L, campaign, 10)));

        List<CandidateAd> candidates = candidateSource.findCandidates(request());

        assertThat(candidates).hasSize(2);
        assertThat(candidates.get(0).campaign()).isSameAs(candidates.get(1).campaign());
    }
}